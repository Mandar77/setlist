"""Compute jiwer's CER and WER for the shared fixture corpus.

    python -m ocr_metrics_oracle --write    # regenerate golden/metric-expected.json
    python -m ocr_metrics_oracle            # fail if it is out of date

The cases are plain JSON, shared verbatim with the TypeScript test, so both sides grade
the same inputs. The expected values are committed: CI must be able to run the
differential without installing jiwer into the Node job, and a reviewer should be able to
see a metric change as a diff rather than as a number that moved somewhere.

**jiwer's defaults are the contract, not an implementation detail.** `jiwer.wer` and
`jiwer.cer` each apply a default transform - whitespace runs collapsed, the string
stripped - before measuring. The TypeScript side has to match that, and the only reliable
way to know what it does is to ask it rather than to read about it. That is what this
file is for: the fixtures below deliberately include double spaces, leading and trailing
whitespace, newlines, an empty reference and a non-BMP character, so the TypeScript
implementation is pinned on exactly the edges where a reimplementation drifts.
"""

from __future__ import annotations

import json
import sys
from importlib.metadata import version
from pathlib import Path
from typing import Any, TypedDict

import jiwer

#: The transform, stated rather than inherited.
#:
#: jiwer's DEFAULTS are wrong for this corpus in two ways, and both were found by running
#: it rather than by reading about it:
#:
#:   * its word splitter splits on SPACES, not on newlines, so "line one\nline two" is
#:     three words and an engine that merged every line would be rewarded for it;
#:   * its CER strips the ends of a string but leaves internal whitespace runs, so an
#:     engine that emits double spaces is charged an error per extra space.
#:
#: Neither is what M2 is grading. Line breaking and spacing are layout, not text: an OCR
#: engine that reads every character correctly and breaks a line differently has not made
#: a reading error. So all whitespace - newlines included - collapses to one space and the
#: ends are stripped, on both metrics and on both sides of the differential.
#:
#: This keeps "measured with jiwer" (PED §670) literally true: jiwer still computes the
#: number. What changed is that the transform is a reviewed decision in this file instead
#: of whatever the library happens to default to in the version we pinned.
_COLLAPSE = jiwer.Compose(
    [
        jiwer.SubstituteRegexes({r"\s+": " "}),
        jiwer.Strip(),
    ]
)
WORD_TRANSFORM = jiwer.Compose([_COLLAPSE, jiwer.ReduceToListOfListOfWords()])
CHAR_TRANSFORM = jiwer.Compose([_COLLAPSE, jiwer.ReduceToListOfListOfChars()])

#: Shared with the TypeScript test. Both sides grade identical inputs or the differential
#: is comparing two different questions.
GOLDEN_DIR = Path(__file__).resolve().parents[3] / "golden"
CASES_PATH = GOLDEN_DIR / "metric-cases.json"
EXPECTED_PATH = GOLDEN_DIR / "metric-expected.json"


class MetricCase(TypedDict):
    """One reference/hypothesis pair, named so a failure says which edge broke."""

    name: str
    reference: str
    hypothesis: str


def load_cases(path: Path = CASES_PATH) -> list[MetricCase]:
    """Read the shared fixture corpus."""
    return json.loads(path.read_text(encoding="utf-8"))["cases"]


def expected_for(cases: list[MetricCase]) -> dict[str, Any]:
    """Compute jiwer's answer for every case.

    An empty reference does not raise: jiwer divides by a guarded denominator rather than
    by zero, so "" against "invented text" comes back as 13.0 - thirteen errors over a
    denominator of one - instead of as an exception or a 0/0. That convention is recorded
    here and matched on the TypeScript side, because it is both aggregatable and honest
    about direction: a page with nothing on it and an engine that read something off it is
    maximally wrong, not perfectly right.
    """
    results = []
    for case in cases:
        reference, hypothesis = case["reference"], case["hypothesis"]
        results.append(
            {
                "name": case["name"],
                "cer": float(
                    jiwer.cer(
                        reference,
                        hypothesis,
                        reference_transform=CHAR_TRANSFORM,
                        hypothesis_transform=CHAR_TRANSFORM,
                    )
                ),
                "wer": float(
                    jiwer.wer(
                        reference,
                        hypothesis,
                        reference_transform=WORD_TRANSFORM,
                        hypothesis_transform=WORD_TRANSFORM,
                    )
                ),
            }
        )

    return {
        "$comment": (
            "GENERATED by tools/ocr-eval/oracle-py. jiwer's answers for "
            "golden/metric-cases.json under the transform stated in metrics.py; the "
            "TypeScript metrics are diffed against them (ADR-014). Run "
            "`make ocr-metrics-write` to regenerate."
        ),
        # Pinned, and recorded in the artifact: if jiwer moves, the diff says so rather
        # than the numbers quietly changing underneath the gate.
        "jiwer": version("jiwer"),
        "results": results,
    }


def main(argv: list[str]) -> int:
    """Entry point: write the expected values, or verify they are current."""
    write = "--write" in argv[1:]
    cases = load_cases()
    expected = expected_for(cases)
    rendered = json.dumps(expected, indent=2, ensure_ascii=False) + "\n"

    if write:
        # newline="\n": `make verify` rejects CRLF, and Python translates on Windows.
        EXPECTED_PATH.write_text(rendered, encoding="utf-8", newline="\n")
        print(f"ocr metrics oracle: wrote {EXPECTED_PATH.name} for {len(cases)} cases")
        return 0

    if not EXPECTED_PATH.exists():
        print(f"{EXPECTED_PATH.name} is missing - run `make ocr-metrics-write`")
        return 1

    if EXPECTED_PATH.read_text(encoding="utf-8") != rendered:
        print(
            f"{EXPECTED_PATH.name} disagrees with jiwer. Either the fixtures changed and "
            "the file was not regenerated, or jiwer moved - and if jiwer moved, the "
            "TypeScript metrics have to move with it. Run `make ocr-metrics-write` and "
            "read the diff before accepting it."
        )
        return 1

    print(f"ocr metrics oracle: {EXPECTED_PATH.name} is current for {len(cases)} cases")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
